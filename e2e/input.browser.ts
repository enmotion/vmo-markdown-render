test('纯文本剪贴板、结构化复制、输入法和禁用只读', async ({ page }) => {
  await clear(page);
  const editor = page.getByRole('textbox', { name: '输入消息…' });
  await editor.focus(); await press(page, editor, 'Control+k'); await press(page, editor, 'Enter');
  await press(page, editor, process.platform === 'darwin' ? 'Meta+a' : 'Control+a');
  const clipboard = await editor.evaluate(element => {
    const data = new DataTransfer();
    element.dispatchEvent(new ClipboardEvent('copy', { clipboardData: data, bubbles: true, cancelable: true }));
    return { text: data.getData('text/plain'), structured: data.getData('application/x-vmo-markdown-input+json') };
  });
  expect(clipboard.text).toContain('@产品知识库');
  await clear(page); await editor.focus();
  await editor.evaluate((element, data) => {
    const transfer = new DataTransfer(); transfer.setData('application/x-vmo-markdown-input+json', data.structured);
    element.dispatchEvent(new ClipboardEvent('paste', { clipboardData: transfer, bubbles: true, cancelable: true }));
  }, clipboard);
  await expect(editor.locator('[data-mention]')).toHaveCount(1);
  await editor.evaluate(element => { element.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true })); });
  await press(page, editor, 'Enter');
  await expect(page.locator('.input-lab__messages article')).toHaveCount(0);
  await editor.evaluate(element => { element.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true })); });
  await page.getByLabel('只读', { exact: true }).check();
  await expect(editor).toHaveAttribute('contenteditable', 'false');
  await expect(editor.getByRole('button')).toHaveCount(0);
  await page.getByLabel('只读', { exact: true }).uncheck();
  await page.getByLabel('禁用', { exact: true }).check();
  await expect(editor).toHaveAttribute('aria-disabled', 'true');
});
