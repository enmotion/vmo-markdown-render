import { expect, test } from '@playwright/test';

test.beforeEach(async ({ page }) => { await page.goto('/'); });
async function press(page: import('@playwright/test').Page, editor: import('@playwright/test').Locator, key: string) {
  const query = page.getByRole('textbox', { name: '搜索引用', exact: true });
  await (await query.isVisible() ? query : editor).press(key);
}
async function clear(page: import('@playwright/test').Page) { await page.getByRole('button', { name: '清空', exact: true }).click(); }
